from rest_framework import permissions


class IsOwnerOrReadOnly(permissions.BasePermission):
    """
    ================================================================================
    提交记录对象级权限控制
    ================================================================================
    
    【功能说明】
    防止学生修改其他同学的提交记录。
    教师可以修改所有学生的提交记录（用于批改和纠错）。
    超级管理员可以修改所有记录。
    
    【权限规则】
    - 读取操作（GET, HEAD, OPTIONS）：所有认证用户允许
    - 写入操作（PUT, PATCH, DELETE）：根据角色判断权限
    
    【使用场景】
    用于 SubmissionViewSet，防止学生通过API直接修改其他同学的答案
    
    【权限判断逻辑】
    1. 超级管理员（is_superuser=True）：可以修改所有记录
    2. 教师（role='teacher'）：可以修改所有学生的记录
    3. 学生（role='student'）：只能修改自己的记录
    
    【为什么需要对象级权限？】
    - get_queryset() 已经过滤了列表查询
    - 但对象级权限用于保护单个对象的操作
    - 比如：学生A尝试 PUT /api/submissions/999/ 修改学生B的记录
    
    ⚠️ 运维注意：
    - 这是核心安全权限类，不要随意修改判断逻辑
    - 删除此权限类会导致学生可以修改其他同学的答案
    - 如需添加新的角色权限，请在对应位置添加分支
    ================================================================================
    """
    
    def has_object_permission(self, request, view, obj):
        """
        ================================================================================
        检查用户是否有权限操作指定的对象
        
        【参数说明】
        - request: 当前HTTP请求对象
        - view: 当前视图对象
        - obj: 被访问的数据库对象（这里是Submission记录）
        
        【返回值】
        - True: 有权限操作，允许访问
        - False: 无权限操作，拒绝访问（返回403）
        
        ⚠️ 运维注意：
        - 不要删除 obj.student == user 的检查
        - 这是防止学生修改其他同学答案的关键逻辑
        ================================================================================
        """
        
        # 📖 读取操作允许所有认证用户
        # 学生可以查看自己的提交记录（已在get_queryset中过滤）
        # 这里主要是为了API的完整性，实际查询权限由get_queryset控制
        if request.method in permissions.SAFE_METHODS:
            return True
        
        # ✍️ 写入操作需要严格权限检查
        user = request.user
        
        # 🔧 超级管理员可以修改所有记录（系统维护需要）
        # 
        # 使用场景：
        # - 后台管理员需要修正学生成绩
        # - 数据修复和清理
        # - 系统调试
        if user.is_superuser:
            return True
        
        # 👩‍🏫 教师可以修改所有学生的提交记录
        # 
        # 使用场景：
        # - 批改试卷
        # - 纠正学生答案错误
        # - 特殊情况处理
        #
        # ⚠️ 注意：教师只能通过API修改，不能代替学生提交
        role = getattr(user, 'role', 'student')
        if role == 'teacher':
            return True
        
        # 👨‍🎓 学生只能修改自己的提交记录
        # 
        # 这是关键安全检查！
        # 确保学生A无法修改学生B的答案
        #
        # ⚠️ 运维注意：
        # - 不要删除这行代码，否则会导致严重的安全漏洞
        # - obj.student 是外键关联的学生对象
        return obj.student == user


class IsStudentOrReadOnly(permissions.BasePermission):
    """
    ================================================================================
    学生专属操作权限控制
    ================================================================================
    
    【功能说明】
    读取操作：所有认证用户允许
    写入操作：只有学生角色可以执行
    
    【使用场景】
    用于只有学生才能执行的操作，比如提交答案
    教师和管理员不能代替学生提交答案
    
    【为什么教师不能提交？】
    - 提交记录需要关联到学生（student字段）
    - 教师提交会导致记录关联到教师账户
    - 统计数据会变得混乱
    
    ⚠️ 运维注意：
    - 如需允许教师代替学生提交，请联系开发人员
    - 这需要修改业务逻辑，不仅仅是权限问题
    ================================================================================
    """
    
    def has_permission(self, request, view):
        """
        ================================================================================
        检查用户是否有执行操作的权限
        
        【参数说明】
        - request: 当前HTTP请求对象
        - view: 当前视图对象
        
        【返回值】
        - True: 有权限操作，允许访问
        - False: 无权限操作，拒绝访问（返回403）
        
        ⚠️ 运维注意：
        - 这是视图级别的权限检查
        - 修改返回值会影响整个视图的访问控制
        ================================================================================
        """
        
        # 📖 读取操作允许所有认证用户
        if request.method in permissions.SAFE_METHODS:
            return True
        
        # ✍️ 写入操作只有学生可以执行
        user = request.user
        role = getattr(user, 'role', 'student')
        
        # 防止教师和管理员代替学生提交答案
        # 
        # ⚠️ 运维注意：
        # - 不要修改 role == 'student' 的判断
        # - 如需允许教师提交，需要同时修改模型和业务逻辑
        return role == 'student'
